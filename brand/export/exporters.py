@dataclass
class AssetRecord:
    """One file in the package, and enough metadata to trace it."""

    name: str
    type: str
    path: str
    format: str
    brand: str
    brand_version: str
    extra: dict[str, Any]

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "type": self.type,
            "path": self.path,
            "format": self.format,
            "brand": self.brand,
            "brand_version": self.brand_version,
            **self.extra,
        }


class AssetInventory:
    """Collects every generated file with its metadata.

    The inventory is what makes the package auditable: the consistency check
    reads it, and a human can see at a glance which artefacts came from which
    brand version. An asset without a record is an asset nobody can trace back
    to a decision.
    """

    def __init__(self, brand: Brand, root: Path | str) -> None:
        self.brand = brand
        self.root = Path(root)
        self._records: list[AssetRecord] = []

    def add(
        self, path: Path | str, *, type: str, name: str | None = None,
        **extra: Any,
    ) -> Path:
        p = Path(path)
        rel = p.relative_to(self.root) if p.is_absolute() else p
        self._records.append(
            AssetRecord(
                name=name or p.stem,
                type=type,
                path=str(rel).replace("\\", "/"),
                format=p.suffix.lstrip("."),
                brand=self.brand.identity.name,
                brand_version=self.brand.version,
                extra=extra,
            )
        )
        return p

    def extend(self, records: Iterable[dict[str, Any]], *, type: str) -> None:
        for record in records:
            self._records.append(
                AssetRecord(
                    name=record.get("name", ""),
                    type=type,
                    path=record.pop("path", ""),
                    format=record.get("format", ""),
                    brand=self.brand.identity.name,
                    brand_version=self.brand.version,
                    extra={
                        k: v for k, v in record.items()
                        if k not in ("name", "format")
                    },
                )
            )

    @property
    def records(self) -> list[AssetRecord]:
        return list(self._records)

    def by_type(self) -> dict[str, list[AssetRecord]]:
        out: dict[str, list[AssetRecord]] = {}
        for r in self._records:
            out.setdefault(r.type, []).append(r)
        return out

    def to_dict(self) -> dict[str, Any]:
        return {
            "brand": self.brand.identity.name,
            "brand_id": str(self.brand.brand_id),
            "brand_version": self.brand.version,
            "brand_status": self.brand.status.value,
            "content_hash": self.brand.content_hash,
            "ados_edition": self.brand.ados_edition,
            "asset_count": len(self._records),
            "assets": [r.to_dict() for r in self._records],
        }

    def write(self, path: Path | str | None = None) -> Path:
        p = Path(path) if path else self.root / "asset-inventory.json"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(self.to_dict(), indent=2) + "\n")
        return p
