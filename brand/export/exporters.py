"""
brand/export/exporters.py

Getting the brand out of ADOS and into the tools that consume it.

Every exporter takes a :class:`TokenSet` (or a :class:`Brand` where the export
is of the definition itself) and writes a file. None of them re-derives a
value: an exporter that computed anything would be a second implementation of
the resolver, and the two would diverge on the first change.

Two of the exporters need a browser. Rasterising an SVG and printing HTML to
PDF are both jobs a browser already does correctly, and reimplementing either
would mean shipping a second, worse renderer. Chromium is optional: where it
is absent the exporter says so and the rest of the package still builds, in
the same way ``pyshacl`` is optional to the rule engine.
"""

from __future__ import annotations

import json
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable

from brand.models.brand import Brand
from brand.models.tokens import TokenSet

#: Where the bundled Chromium lives in this environment. Checked, never assumed.
_CHROMIUM_CANDIDATES = (
    "/opt/pw-browsers/chromium",
    "/usr/bin/chromium",
    "/usr/bin/chromium-browser",
    "/usr/bin/google-chrome",
)


class ExportUnavailable(RuntimeError):
    """An export needs a tool that is not installed."""


