def chromium_path() -> str | None:
    """The browser to use, or ``None``. Never guesses."""
    for candidate in _CHROMIUM_CANDIDATES:
        if Path(candidate).exists():
            return candidate
    return shutil.which("chromium") or shutil.which("google-chrome")


def browser_available() -> bool:
    if chromium_path() is None:
        return False
    try:
        import playwright.sync_api  # noqa: F401
    except ImportError:
        return False
    return True


@dataclass
class RasterResult:
    path: Path | None
    ok: bool
    reason: str = ""


def rasterise_svg(
    svg_path: Path | str, png_path: Path | str, *, width_px: int = 1200
) -> RasterResult:
    """SVG → PNG at a stated pixel width.

    A PNG is needed wherever SVG is not accepted — an email signature, a social
    post, a Word document. It is a derived artefact and the SVG remains the
    master; the manifest records both so nobody edits the raster.
    """
    svg_path, png_path = Path(svg_path), Path(png_path)
    if not browser_available():
        return RasterResult(
            None, False,
            "no Chromium and/or playwright available; the SVG is the master "
            "and the PNG can be produced later with "
            "`python -m brand.cli rasterise`",
        )
    from playwright.sync_api import sync_playwright

    # Preserve the aspect ratio declared by the SVG's own viewBox.
    import re

    text = svg_path.read_text()
    m = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', text)
    ratio = (float(m.group(2)) / float(m.group(1))) if m else 1.0
    height_px = max(1, round(width_px * ratio))

    png_path.parent.mkdir(parents=True, exist_ok=True)
    page_html = (
        f"<html><body style='margin:0'>"
        f"<img src='{svg_path.name}' style='width:{width_px}px;display:block'>"
        f"</body></html>"
    )
    holder = svg_path.parent / f".raster-{svg_path.stem}.html"
    holder.write_text(page_html)
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch(executable_path=chromium_path())
            page = browser.new_page(
                viewport={"width": width_px, "height": height_px},
                device_scale_factor=1,
            )
            page.goto(holder.as_uri())
            page.screenshot(path=str(png_path), omit_background=True)
            browser.close()
    finally:
        holder.unlink(missing_ok=True)
    return RasterResult(png_path, True)


def html_to_pdf(
    html_path: Path | str, pdf_path: Path | str, *,
    page_format: str = "A4", landscape: bool = False,
    margin_mm: float = 0.0,
) -> RasterResult:
    """Print an HTML page to PDF through the browser's own print path.

    Used for the guidelines and the presentation. The alternative — laying the
    same content out a second time in reportlab — would mean two renderers
    that must be kept saying the same thing, and they would not.
    """
    html_path, pdf_path = Path(html_path), Path(pdf_path)
    if not browser_available():
        return RasterResult(
            None, False,
            "no Chromium and/or playwright available; the HTML is complete and "
            "print-ready — use the browser's Print to PDF, or install "
            "playwright to automate it",
        )
    from playwright.sync_api import sync_playwright

    pdf_path.parent.mkdir(parents=True, exist_ok=True)
    margin = f"{margin_mm}mm"
    with sync_playwright() as pw:
        browser = pw.chromium.launch(executable_path=chromium_path())
        page = browser.new_page()
        page.goto(html_path.as_uri())
        page.emulate_media(media="print")
        page.pdf(
            path=str(pdf_path),
            format=page_format,
            landscape=landscape,
            print_background=True,
            margin={"top": margin, "bottom": margin,
                    "left": margin, "right": margin},
        )
        browser.close()
    return RasterResult(pdf_path, True)


