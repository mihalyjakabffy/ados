def to_css_variables(tokens: TokenSet, *, selector: str = ":root") -> str:
    """CSS custom properties.

    Token names become kebab-case custom properties under one selector, so a
    stylesheet written against them tracks the brand without a build step.
    Millimetre values keep their unit — a length exported as a bare number is
    a length the browser will guess about.
    """
    lines = [
        "/* Generated by the ADOS Brand System. Do not edit.",
        f"   brand {tokens.brand_version} · {len(tokens)} tokens",
        "   Every value here is resolved from the brand; change the brand, not",
        "   this file. */",
        f"{selector} {{",
    ]
    for name, token in tokens.items():
        if isinstance(token.value, (list, dict)):
            continue                      # not expressible as a CSS value
        value = token.value
        if token.unit.value == "mm":
            value = f"{value}mm"
        elif token.unit.value == "pt":
            value = f"{value}pt"
        elif token.unit.value == "percent":
            value = f"{value}%"
        elif isinstance(value, bool):
            value = "1" if value else "0"
        lines.append(f"  --{name.replace('.', '-')}: {value};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def to_json(tokens: TokenSet, *, flat: bool = False) -> str:
    """Tokens as JSON — flat values, or the full record with provenance."""
    payload = tokens.flat() if flat else tokens.to_json_dict()
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def to_yaml(brand: Brand) -> str:
    """The brand definition as YAML.

    YAML because the repository's standards packs are YAML and a practice
    editing its brand by hand will find it friendlier than JSON. Falls back to
    JSON — which is valid YAML — when PyYAML is absent, rather than failing.
    """
    payload = json.loads(brand.to_json())
    try:
        import yaml
    except ImportError:                                    # pragma: no cover
        return (
            "# PyYAML is not installed; emitted as JSON, which is valid YAML.\n"
            + json.dumps(payload, indent=2)
            + "\n"
        )
    header = (
        f"# {brand.identity.name} — brand {brand.version} ({brand.status.value})\n"
        f"# Generated by the ADOS Brand System. content_hash "
        f"{brand.content_hash}\n"
    )
    return header + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)


def to_colour_table(tokens: TokenSet) -> list[dict[str, Any]]:
    """The palette with HEX, RGB, CMYK and L\\*, for a specification sheet.

    CMYK is a naive conversion and is labelled as such. A real print job takes
    its separations from a profiled conversion against the actual press and
    stock; a number produced here would be a number someone trusts. It is
    included because a printer asks for a starting point, not a final one.
    """
    from brand import colour as _c

    rows: list[dict[str, Any]] = []
    for name, token in sorted(tokens.namespace("color").items()):
        if not isinstance(token.value, str) or not token.value.startswith("#"):
            continue
        hex_value = token.value
        r, g, b = _c.to_rgb(hex_value)
        rows.append(
            {
                "token": name,
                "hex": hex_value,
                "rgb": f"{r} {g} {b}",
                "cmyk_uncalibrated": _naive_cmyk(r, g, b),
                "L_star": round(_c.l_star(hex_value), 1),
                "mono": _c.to_greyscale_hex(hex_value),
                "source": token.source,
            }
        )
    return rows


def _naive_cmyk(r: int, g: int, b: int) -> str:
    if (r, g, b) == (0, 0, 0):
        return "0 0 0 100"
    rc, gc, bc = r / 255, g / 255, b / 255
    k = 1 - max(rc, gc, bc)
    c = (1 - rc - k) / (1 - k)
    m = (1 - gc - k) / (1 - k)
    y = (1 - bc - k) / (1 - k)
    return " ".join(str(round(v * 100)) for v in (c, m, y, k))


